def make_job_posting(rng: random.Random, *, with_duties: bool) -> tuple[str, str, str]:
    """返回 (title, company, raw_text)。with_duties=True 时带 2-4 句职责，专业可推断（裁决#2）。"""
    company = make_company(rng)
    city = rng.choice(["北京", "上海", "深圳", "杭州", "广州", "成都", "西安", "武汉", "南京", "苏州"])
    degree = rng.choice(["本科及以上", "本科以上，硕士优先", "全日制本科", "硕士及以上"])
    smin = rng.choice([6, 8, 10, 12, 15, 18])
    smax = smin + rng.choice([4, 6, 8, 10])
    hc = rng.choice([1, 2, 3, 5, 8])
    if with_duties:
        title, duties, major_hint = rng.choice(_JOB_ARCHETYPES)
        picked = rng.sample(duties, k=rng.randint(2, min(3, len(duties))))
        duty_text = "；".join(picked) + "。"
        raw = (f"【{title}】{company}\n岗位职责：{duty_text}\n"
               f"任职要求：{degree}，{major_hint}等相关专业优先。\n"
               f"工作地点：{city}。薪资 {smin}-{smax}k/月，招聘 {hc} 人。")
        return title, company, raw
    # 精简岗位（约束外的少数，专业无从推断 → 应进人工复核）
    title = make_job_title(rng)
    raw = f"{company}诚聘{title}，要求{degree}，薪资{smin}-{smax}k，工作地点{city}。"
    return title, company, raw
